#!/usr/bin/env python3
"""Write the server SQL for the Northrend Skeleton and Ice Troll NPC displays.

Pandaren use races 20 and 21, which are the Northrend Skeleton and the Ice Troll
in CreatureDisplayInfoExtra. The client patch moves those NPC displays to Vrykul
(16) and Troll (8) (tools/npcdisplays.py explains the choice). This writes the
same rows for the server's `creaturedisplayinfoextra_dbc` and `charsections_dbc`,
so both halves agree.

    gen-npc-displays.py --dbc <the client's DBFilesClient> --out <file.sql>

--dbc needs CreatureDisplayInfoExtra, CreatureDisplayInfo, CharSections,
CharHairGeosets and CharacterFacialHairStyles as the server loads them. The
files are copied first and never changed.
"""
import argparse
import os
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import npcdisplays as nd   # noqa: E402

NEEDED = ['CreatureDisplayInfoExtra', 'CreatureDisplayInfo', 'CharSections', 'CharHairGeosets',
          'CharacterFacialHairStyles']


def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def write_sql(path, extras, cs, cs_ids, source):
    ids = sorted(v[0] for v, _ in extras)
    out = [
        '-- GENERATED by tools/gen-npc-displays.py -- do not edit by hand.',
        '--',
        '-- The Northrend Skeleton (race 20) and Ice Troll (21) NPC displays, moved to',
        '-- Vrykul (16) and Troll (8) because pandaren use 20 and 21. Same rows as the',
        "-- client patch; tools/npcdisplays.py explains the choice of race.",
        '--',
        '-- The server reads DisplayRaceID for holiday costume auras and for whether',
        '-- a transformed player may mount (Unit.cpp); the textures only to keep both',
        '-- halves identical.',
        '--',
        f'-- The rows are generated from {source}.',
        '-- If your DBC files differ (another patch that touches these displays),',
        '-- regenerate this file from yours.',
        '',
        'DELETE FROM `creaturedisplayinfoextra_dbc` WHERE `ID` IN (%s);' % ', '.join(map(str, ids)),
        'INSERT INTO `creaturedisplayinfoextra_dbc` (%s) VALUES' % ', '.join('`%s`' % c for c in nd.X_COLUMNS),
    ]
    vals = []
    for v, bake in sorted(extras):
        vals.append('  (%s, %s)' % (', '.join(str(x) for x in v[:nd.X_BAKE]), q(bake)))
    out.append(',\n'.join(vals) + ';')
    out += [
        '',
        "-- Vrykul male skin colours 0-3 carry the skeleton's bone texture as their",
        '-- second texture; VrykulMale.m2 has no slot for it, so vrykul are unchanged.',
        '-- No column list: some databases and a fresh one name the columns',
        '-- differently and the core reads them by position (ID, RaceID, SexID,',
        '-- BaseSection, TextureName_1-3, Flags, VariationIndex, ColorIndex).',
        'DELETE FROM `charsections_dbc` WHERE `ID` IN (%s);' % ', '.join(map(str, cs_ids)),
        'INSERT INTO `charsections_dbc` VALUES',
    ]
    rows = {cs.ints(r)[0]: cs.ints(r) for r in cs.rows}
    vals = []
    for i in cs_ids:
        v = rows[i]
        vals.append('  (%d, %d, %d, %d, %s, %s, %s, %d, %d, %d)' % (
            v[0], v[1], v[2], v[3], q(cs.s(v[4])), q(cs.s(v[5])), q(cs.s(v[6])), v[7], v[8], v[9]))
    out.append(',\n'.join(vals) + ';')
    out += [
        '',
        '-- Check: %d.' % len(ids),
        '--   SELECT COUNT(*) FROM creaturedisplayinfoextra_dbc WHERE DisplayRaceID IN (8, 16);',
        '',
    ]
    with open(path, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(out))
    print(f'  {path}: {len(ids)} extra rows, {len(cs_ids)} CharSections rows')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dbc', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--source', default='an unmodified 3.3.5a client',
                    help='what the input is, for the file header')
    a = ap.parse_args()
    work = tempfile.mkdtemp(prefix='npcdisplays-')
    try:
        for n in NEEDED:
            shutil.copy2(nd.find(a.dbc, n + '.dbc'), os.path.join(work, n + '.dbc'))
        src = os.path.join(work, 'CreatureDisplayInfoExtra.dbc')
        shutil.move(src, src + '.src')
        extras, cs, cs_ids, log = nd.fix(work, src + '.src', src)
        for line in log:
            print('  ' + line)
        write_sql(a.out, extras, cs, cs_ids, a.source)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == '__main__':
    main()
